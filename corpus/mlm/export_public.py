"""corpus/mlm/export_public.py — 公開用リポジトリ(ja-ai-style-corpus)にデータを書き出す。

書き出すもの:
    data/baseline/qiita-pre2022.jsonl       AI 以前(2019〜2022年8月)の Qiita 記事の一覧(ID・URL・タイトルなど。本文なし)
    data/baseline/qiita-2026.jsonl          2026年8月の Qiita 記事の一覧(同上)
    data/baseline/llmjp-explanatory-pre2022-v1.jsonl  LLM-jp 由来の生成AI以前の説明的な Web 文章の一覧(本文なし)
    data/generated/generated-v1.jsonl.gz    話題をそろえて3社に書かせた文章(本文と出どころつき。内容は架空)
    data/generated/sources-v1.jsonl         各プロンプトの元になった人間の文書の所在(本文なし)
    data/eval/generated-holdout-v0.jsonl.gz 検査用の生成記事100本(学習に使っていない。別の実験で7モデルに書かせたもの)
    data/eval/test-*.txt                    検査に使った人間の文書の ID(学習から除いた)

人間の文書の本文は含めない(著作権は書いた人にある)。一覧から取り出すスクリプトを scripts/ に置く。
生成文は全件に synthetic: true と notice を付ける。本文は手を加えない版(text)と、
チャットの前置きや伏せ字のひな形を除いた版(text_clean。mlm_contrast.clean_generated)の両方を入れる。

使い方: uv run corpus/mlm/export_public.py --out ~/progs/oss/ja-ai-style-corpus --tags prod prod2
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
GEN = ROOT / "corpus/private/mlm/gen"
DATA = ROOT / "corpus/timeslice/qiita-aug/data"
sys.path.insert(0, str(HERE))
from mlm_contrast import clean_generated  # noqa: E402

NOTICE = ("この文章は、生成AIに書かせた合成データです。実在の組織名・人名・製品名が出てきても、"
          "内容(日付・数値・発表・発言など)は架空で、事実ではありません。"
          "This text is synthetic, generated by an AI model. Any real organizations or people mentioned are used fictitiously.")


def qiita_rows(years):
    for y in years:
        for l in gzip.open(DATA / f"{y}.jsonl.gz", "rt", encoding="utf-8"):
            d = json.loads(l)
            yield {"id": d["id"], "year": d["year"], "created_at": d["created_at"], "title": d["title"],
                   "url": f"https://qiita.com/{d['author']}/items/{d['id']}", "tags": d.get("tags"),
                   "likes": d.get("likes"), "stocks": d.get("stocks"), "prose_chars": d.get("prose_chars"),
                   "body_sha256": hashlib.sha256(d["body"].encode("utf-8")).hexdigest()}


def write_jsonl(path: Path, rows) -> int:
    """.gz で終わるパスは gzip で書く(GitHub の1ファイル100MBの上限に収めるため)。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "wt", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
            n += 1
    return n


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--tags", nargs="+", default=["prod", "prod2"])
    a = ap.parse_args()
    out = Path(a.out).expanduser()

    n = write_jsonl(out / "data/baseline/qiita-pre2022.jsonl", qiita_rows([2019, 2020, 2021, 2022]))
    print(f"qiita-pre2022: {n}")
    n = write_jsonl(out / "data/baseline/qiita-2026.jsonl", qiita_rows([2026]))
    print(f"qiita-2026: {n}")
    shutil.copy(ROOT / "corpus/llmjp/manifest/explanatory-pre2022-v1.jsonl", out / "data/baseline/llmjp-explanatory-pre2022-v1.jsonl")

    # プロンプトの元の所在
    qiita_index = {r["id"]: r for r in qiita_rows([2019, 2020, 2021])}
    llmjp_index = {}
    for f in sorted((ROOT / "corpus/private/llmjp").glob("level0-*.scored.jsonl")):
        for l in open(f, encoding="utf-8"):
            d = json.loads(l)
            llmjp_index[d["docId"]] = {k: d[k] for k in ("source", "docId", "url", "date", "type", "sha256", "score")}
    gen_rows, src_rows = [], []
    for tag in a.tags:
        prompts = {p["id"]: p for p in json.loads((GEN / f"prompts-{tag}.json").read_text(encoding="utf-8"))}
        for p in prompts.values():
            if p["src"] == "qiita":
                q = qiita_index.get(p["id"][2:], {})
                src_rows.append({"prompt_id": p["id"], "kind": "qiita", "qiita_id": p["id"][2:], "title": q.get("title"),
                                 "url": q.get("url"), "body_sha256": q.get("body_sha256"), "batch": tag})
            else:
                src_rows.append({"prompt_id": p["id"], "kind": "llmjp", **llmjp_index.get(p["id"][2:], {"docId": p["id"][2:]}), "batch": tag})
        for l in open(GEN / tag / "meta.jsonl", encoding="utf-8"):
            m = json.loads(l)
            f = GEN / tag / m["engine"] / f"{m['id']}.md"
            if not f.exists():
                continue
            text = f.read_text(encoding="utf-8")
            gen_rows.append({"id": f"{tag}/{m['engine']}/{m['id']}", "prompt_id": m["id"], "batch": tag, "src": m["src"],
                             "type": m.get("type"), "vendor": m["vendor"], "model": m["model"],
                             "model_version": m.get("model_version"), "effort": m["effort"], "harness": m["harness"],
                             "harness_version": m["harness_version"], "settings": m["settings"], "prompt": m["prompt"],
                             "generated_at": m["generated_at"], "backfilled": m.get("backfilled", False), "text": text, "text_clean": clean_generated(text),
                             "synthetic": True, "notice": NOTICE})
    n = write_jsonl(out / "data/generated/generated-v1.jsonl.gz", gen_rows)
    print(f"generated: {n}")
    n = write_jsonl(out / "data/generated/sources-v1.jsonl", src_rows)
    print(f"sources: {n}")
    export_eval(out)


def parse_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    head, body = text[4:].split("\n---\n", 1)
    meta = {}
    for l in head.split("\n"):
        k, _, v = l.partition(": ")
        meta[k] = json.loads(v) if v else None
    return meta, body.strip()


def export_eval(out: Path) -> None:
    """mlm_contrast.py prepare が作った検査用の文書を、本文から ID に戻して書き出す。作者の文書(self)は非公開。"""
    tests = json.loads((ROOT / "corpus/private/mlm/tests.json").read_text(encoding="utf-8"))
    by_body = {}
    for y in (2022, 2026):
        for l in gzip.open(DATA / f"{y}.jsonl.gz", "rt", encoding="utf-8"):
            d = json.loads(l)
            by_body[d["body"]] = d["id"]
    for f in sorted((ROOT / "corpus/private/llmjp").glob("level0-*.scored.jsonl")):
        for l in open(f, encoding="utf-8"):
            d = json.loads(l)
            by_body[d["text"]] = d["docId"]
    (out / "data/eval").mkdir(parents=True, exist_ok=True)
    for name in ("qiita2022", "qiita2026", "llmjp"):
        ids = [by_body[t] for t in tests[name] if t in by_body]
        (out / f"data/eval/test-{name}.txt").write_text("\n".join(ids) + "\n", encoding="utf-8")
        print(f"test-{name}: {len(ids)} / {len(tests[name])}")
    # 検査用の生成記事は corpus/paired/*/ai/<model>/<id>.md(先頭に出どころの記録がある)
    rows = []
    for t in tests["generated_holdout"]:
        meta, body = parse_frontmatter(t)
        harness = {"claude": "Claude Code (claude -p)", "codex": "Codex CLI (codex exec)",
                   "agy": "Antigravity CLI (agy -p)"}.get(meta.get("engine"), meta.get("engine"))
        rows.append({"id": f"{meta.get('set')}/{meta.get('model')}/{meta.get('id')}", "model": meta.get("model"),
                     "effort": meta.get("effort"), "harness": harness, "harness_version": meta.get("cli_version"),
                     "settings": "個人設定を外した環境(空の作業ディレクトリと HOME)。生成文の settings と同じ隔離",
                     "prompt": meta.get("prompt"), "generated_at": meta.get("generated_at"),
                     "text": body, "text_clean": clean_generated(body), "synthetic": True, "notice": NOTICE})
    n = write_jsonl(out / "data/eval/generated-holdout-v0.jsonl.gz", rows)
    print(f"generated-holdout: {n}")


if __name__ == "__main__":
    main()
